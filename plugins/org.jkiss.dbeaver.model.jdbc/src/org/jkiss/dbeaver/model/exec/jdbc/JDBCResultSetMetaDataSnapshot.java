package org.jkiss.dbeaver.model.exec.jdbc;

import org.jkiss.code.NotNull;
import org.jkiss.dbeaver.model.DBPDataSource;
import org.jkiss.dbeaver.model.exec.DBCAttributeMetaData;
import org.jkiss.dbeaver.model.exec.DBCException;
import org.jkiss.dbeaver.model.impl.jdbc.exec.JDBCColumnMetaData;

import java.sql.ResultSetMetaData;
import java.sql.SQLException;
import java.util.ArrayList;
import java.util.Collections;
import java.util.List;
import java.util.Objects;

import javax.sql.rowset.RowSetMetaDataImpl;

/**
 * Column descriptions obtained before opening a streaming result set when
 * {@link DBPDataSource#FEATURE_JDBC_TABLE_READ_REQUIRES_PREPARED_COLUMN_METADATA} is requested.
 */
public final class JDBCResultSetMetaDataSnapshot {
    private final List<Column> columns;
    private final List<String> labels;

    private JDBCResultSetMetaDataSnapshot(@NotNull List<Column> columns, @NotNull List<String> labels) {
        this.columns = List.copyOf(columns);
        // Drivers may return null labels; unlike List.copyOf, this preserves them for validation.
        this.labels = Collections.unmodifiableList(new ArrayList<>(labels));
    }

    public static JDBCResultSetMetaDataSnapshot prepare(JDBCSession jdbcSession, String queryString) throws DBCException {
        try (JDBCPreparedStatement metadataStatement = jdbcSession.prepareStatement(queryString)) {
            return JDBCResultSetMetaDataSnapshot.capture(jdbcSession, metadataStatement);
        } catch (SQLException e) {
            throw new DBCException("Cannot prepare export column metadata", e, jdbcSession.getExecutionContext());
        }
    }

    @NotNull
    public static JDBCResultSetMetaDataSnapshot capture(
        @NotNull JDBCSession session,
        @NotNull JDBCPreparedStatement metadataStatement
    ) throws SQLException, DBCException {
        ResultSetMetaData original = metadataStatement.getMetaData();
        if (original == null) {
            throw new DBCException("Cannot describe the export result before opening its cursor");
        }
        JDBCResultSetMetaData metadata = session.getDataSource().getJdbcFactory().createResultSetMetaData(session, metadataStatement, original);

        List<? extends DBCAttributeMetaData> attributes = metadata.getAttributes();
        int count = attributes.size();
        List<Column> columns = new ArrayList<>(count);
        List<String> labels = new ArrayList<>(count);
        for (int i = 1; i <= count; i++) {
            // Use the factory's resolved columns, including driver-specific base names and
            // its per-property fallbacks. The raw label is only needed to validate the cursor.
            JDBCColumnMetaData column = (JDBCColumnMetaData) attributes.get(i - 1);
            labels.add(original.getColumnLabel(i));
            int nullable;
            try {
                nullable = original.isNullable(i);
            } catch (Throwable e) {
                nullable = ResultSetMetaData.columnNullableUnknown;
            }
            if (nullable < ResultSetMetaData.columnNoNulls || nullable > ResultSetMetaData.columnNullableUnknown) {
                nullable = ResultSetMetaData.columnNullableUnknown;
            }
            columns.add(new Column(
                column.getLabel(), column.getName(), column.getEntityName(), column.getSchemaName(),
                column.getCatalogName(), column.getTypeID(), column.getTypeName(), nullable,
                column.isAutoGenerated(), column.isWritable(), (int) column.getMaxLength(),
                column.getPrecision(), column.getScale()
            ));
        }
        return new JDBCResultSetMetaDataSnapshot(columns, labels);
    }

    /** Checking labels and ordinals does not require the driver's field-metadata query. */
    public void validate(@NotNull ResultSetMetaData actual) throws SQLException {
        if (actual.getColumnCount() != columns.size()) {
            throw new SQLException("Export result columns do not match the prepared metadata");
        }
        for (int i = 1; i <= columns.size(); i++) {
            if (!Objects.equals(labels.get(i - 1), actual.getColumnLabel(i))) {
                throw new SQLException("Export result column " + i + " does not match the prepared metadata");
            }
        }
    }

    @NotNull
    public SnapshotMetaData toMetaData() throws SQLException {
        SnapshotMetaData metadata = new SnapshotMetaData(columns);
        metadata.setColumnCount(columns.size());
        for (int i = 1; i <= columns.size(); i++) {
            Column column = columns.get(i - 1);
            metadata.setColumnLabel(i, column.label());
            metadata.setColumnName(i, column.name());
            metadata.setTableName(i, Objects.toString(column.table(), ""));
            metadata.setSchemaName(i, Objects.toString(column.schema(), ""));
            metadata.setCatalogName(i, Objects.toString(column.catalog(), ""));
            metadata.setColumnType(i, column.type());
            metadata.setColumnTypeName(i, column.typeName());
            metadata.setNullable(i, column.nullable());
            metadata.setAutoIncrement(i, column.autoIncrement());
            metadata.setColumnDisplaySize(i, Math.max(0, column.displaySize()));
            metadata.setPrecision(i, Math.max(0, column.precision()));
            metadata.setScale(i, Math.max(0, column.scale()));
        }
        return metadata;
    }

    private record Column(
        String label, String name, String table, String schema, String catalog, int type, String typeName,
        int nullable, boolean autoIncrement, boolean writable, int displaySize, int precision, int scale
    ) {
    }

    /** Identifies metadata that has already had driver-specific base names resolved. */
    public static class SnapshotMetaData extends RowSetMetaDataImpl {
        private final List<Column> columns;

        private SnapshotMetaData(@NotNull List<Column> columns) {
            this.columns = columns;
        }

        private Column column(int index) throws SQLException {
            if (index < 1 || index > columns.size()) {
                throw new SQLException("Invalid column index: " + index);
            }
            return columns.get(index - 1);
        }

        @Override
        public boolean isWritable(int column) throws SQLException {
            return column(column).writable();
        }

        @Override
        public int getColumnDisplaySize(int column) throws SQLException {
            return column(column).displaySize();
        }

        @Override
        public int getPrecision(int column) throws SQLException {
            return column(column).precision();
        }

        @Override
        public int getScale(int column) throws SQLException {
            return column(column).scale();
        }
    }
}
