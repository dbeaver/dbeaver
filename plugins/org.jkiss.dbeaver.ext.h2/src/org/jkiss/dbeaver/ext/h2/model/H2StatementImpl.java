package org.jkiss.dbeaver.ext.h2.model;

import org.jkiss.code.NotNull;
import org.jkiss.code.Nullable;
import org.jkiss.dbeaver.model.exec.jdbc.JDBCObjectSupplier;
import org.jkiss.dbeaver.model.exec.jdbc.JDBCResultSet;
import org.jkiss.dbeaver.model.impl.jdbc.exec.JDBCStatementImpl;

import java.sql.SQLException;
import java.sql.Statement;

final class H2StatementImpl extends JDBCStatementImpl<Statement> {
    private final H2ConnectionImpl connection;

    H2StatementImpl(
        @NotNull H2ConnectionImpl connection,
        @NotNull JDBCObjectSupplier<Statement> original,
        boolean disableLogging
    ) throws SQLException {
        super(connection, original, null, disableLogging);
        this.connection = connection;
    }

    @Override
    public boolean execute(@NotNull String sql) throws SQLException {
        connection.validateQuery(sql);
        return super.execute(sql);
    }

    @Nullable
    @Override
    public JDBCResultSet executeQuery(@NotNull String sql) throws SQLException {
        connection.validateQuery(sql);
        return super.executeQuery(sql);
    }

    @Override
    public int executeUpdate(String sql) throws SQLException {
        connection.validateQuery(sql);
        return super.executeUpdate(sql);
    }

    @Override
    public int executeUpdate(String sql, int autoGeneratedKeys) throws SQLException {
        connection.validateQuery(sql);
        return super.executeUpdate(sql, autoGeneratedKeys);
    }

    @Override
    public int executeUpdate(String sql, int[] columnIndexes) throws SQLException {
        connection.validateQuery(sql);
        return super.executeUpdate(sql, columnIndexes);
    }

    @Override
    public int executeUpdate(String sql, String[] columnNames) throws SQLException {
        connection.validateQuery(sql);
        return super.executeUpdate(sql, columnNames);
    }

    @Override
    public boolean execute(String sql, int autoGeneratedKeys) throws SQLException {
        connection.validateQuery(sql);
        return super.execute(sql, autoGeneratedKeys);
    }

    @Override
    public boolean execute(String sql, int[] columnIndexes) throws SQLException {
        connection.validateQuery(sql);
        return super.execute(sql, columnIndexes);
    }

    @Override
    public boolean execute(String sql, String[] columnNames) throws SQLException {
        connection.validateQuery(sql);
        return super.execute(sql, columnNames);
    }

    @Override
    public void addBatch(String sql) throws SQLException {
        connection.validateQuery(sql);
        super.addBatch(sql);
    }
}
